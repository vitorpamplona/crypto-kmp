#!/usr/bin/env python3
"""Turns NIST CAVP's KAS ECC CDH primitive vectors for P-256 into Kotlin data for commonTest.

Usage: python3 -I scripts/cavp/generate_ecdh.py <KAS_ECC_CDH_PrimitiveTest.txt>

The file is in https://csrc.nist.gov/CSRC/media/Projects/Cryptographic-Algorithm-Validation-Program/
documents/components/ecccdhtestvectors.zip (a work of the US government, so public domain). Each
vector becomes one '|'-separated string: COUNT|QCAVSx|QCAVSy|dIUT|QIUTx|QIUTy|ZIUT, lowercase hex.
"""

import hashlib
import os
import sys

OUT = os.path.join(
    os.path.dirname(__file__), "..", "..", "crypto", "src", "commonTest", "kotlin",
    "com", "vitorpamplona", "crypto", "ec", "CavpP256Vectors.kt",
)
FIELDS = ["COUNT", "QCAVSx", "QCAVSy", "dIUT", "QIUTx", "QIUTy", "ZIUT"]


def main(src):
    raw = open(src, "rb").read()
    rows, section, vector = [], None, {}
    for line in raw.decode().splitlines():
        line = line.strip()
        if line.startswith("["):
            section = line
            continue
        if section != "[P-256]" or "=" not in line:
            continue
        key, value = (part.strip() for part in line.split("=", 1))
        vector[key] = value.lower()
        if key == "ZIUT":
            rows.append("|".join(vector[f] for f in FIELDS))
            vector = {}
    header = open(os.path.join(os.path.dirname(__file__), "..", "..", "spotless", "copyright.kt")).read()
    lines = [
        header.rstrip("\n"),
        "package com.vitorpamplona.crypto.ec",
        "",
        "// Generated by scripts/cavp/generate_ecdh.py: do not edit.",
        "// NIST CAVP KAS ECC CDH primitive vectors, [P-256] of KAS_ECC_CDH_PrimitiveTest.txt (%d vectors)," % len(rows),
        "// sha256 %s. A work of the US government." % hashlib.sha256(raw).hexdigest(),
        "",
        "/** %s */" % "|".join(FIELDS),
        "internal val CAVP_P256_CDH_VECTORS: Array<String> =",
        "    arrayOf(",
    ]
    lines += ['        "%s",' % row for row in rows]
    lines += ["    )", ""]
    with open(OUT, "w") as out:
        out.write("\n".join(lines))
    print("P-256 %d vectors" % len(rows))


if __name__ == "__main__":
    main(sys.argv[1])
