#!/usr/bin/env python3
"""Turns Project Wycheproof test vectors into Kotlin data for commonTest.

Usage: python3 -I scripts/wycheproof/generate.py <dir with the testvectors_v1 JSON files>

The files come from https://github.com/C2SP/wycheproof/tree/main/testvectors_v1 (Apache
License 2.0). Each vector becomes one '|'-separated string, so the data compiles to a flat
array of constants on every target instead of thousands of object constructions. Fields are
lowercase hex except tcId, result, flags (comma-separated) and sizes. The tests that read them
are in WycheproofTest.kt; rerun this after updating the JSON and commit the output.
"""

import hashlib
import json
import os
import sys

OUT = os.path.join(
    os.path.dirname(__file__), "..", "..", "crypto", "src", "commonTest", "kotlin",
    "com", "vitorpamplona", "crypto", "wycheproof",
)

# Kotlin name, JSON file, the fields of each vector after tcId|result|flags.
SUITES = [
    ("AES_GCM", "aes_gcm_test.json", ["key", "iv", "aad", "msg", "ct", "tag"]),
    ("AES_CBC_PKCS5", "aes_cbc_pkcs5_test.json", ["key", "iv", "msg", "ct"]),
    ("CHACHA20_POLY1305", "chacha20_poly1305_test.json", ["key", "iv", "aad", "msg", "ct", "tag"]),
    ("XCHACHA20_POLY1305", "xchacha20_poly1305_test.json", ["key", "iv", "aad", "msg", "ct", "tag"]),
    ("X25519", "x25519_test.json", ["public", "private", "shared"]),
    ("ECDH_P256", "ecdh_secp256r1_ecpoint_test.json", ["public", "private", "shared"]),
    ("ED25519", "ed25519_test.json", ["@pk", "msg", "sig"]),
    ("HMAC_SHA1", "hmac_sha1_test.json", ["@tagSize", "key", "msg", "tag"]),
    ("HMAC_SHA256", "hmac_sha256_test.json", ["@tagSize", "key", "msg", "tag"]),
    ("HMAC_SHA512", "hmac_sha512_test.json", ["@tagSize", "key", "msg", "tag"]),
    ("HKDF_SHA1", "hkdf_sha1_test.json", ["ikm", "salt", "info", "size", "okm"]),
    ("HKDF_SHA256", "hkdf_sha256_test.json", ["ikm", "salt", "info", "size", "okm"]),
    ("HKDF_SHA512", "hkdf_sha512_test.json", ["ikm", "salt", "info", "size", "okm"]),
]

# Longer strings are split across lines: ktlint allows 5000 characters a line.
CHUNK = 2000


def group_field(group, name):
    if name == "@pk":
        return group["publicKey"]["pk"]
    return str(group[name[1:]])


def kotlin_string(value):
    assert all(c not in value for c in '"\\$'), value
    if len(value) <= CHUNK:
        return '"%s"' % value
    parts = [value[i:i + CHUNK] for i in range(0, len(value), CHUNK)]
    return " +\n            ".join('"%s"' % p for p in parts)


def main(src):
    os.makedirs(OUT, exist_ok=True)
    # The header Spotless puts on every Kotlin file, so its check passes on fresh output.
    header = open(os.path.join(os.path.dirname(__file__), "..", "..", "spotless", "copyright.kt")).read()
    for name, file, fields in SUITES:
        path = os.path.join(src, file)
        raw = open(path, "rb").read()
        data = json.loads(raw)
        rows = []
        for group in data["testGroups"]:
            for test in group["tests"]:
                values = [str(test["tcId"]), test["result"], ",".join(test.get("flags", []))]
                for field in fields:
                    values.append(group_field(group, field) if field.startswith("@") else str(test[field]))
                assert all("|" not in v for v in values)
                rows.append("|".join(values))
        layout = "|".join(["tcId", "result", "flags"] + [f.lstrip("@") for f in fields])
        kt = name.title().replace("_", "")
        lines = [
            header.rstrip("\n"),
            "package com.vitorpamplona.crypto.wycheproof",
            "",
            "// Generated by scripts/wycheproof/generate.py: do not edit.",
            "// Project Wycheproof, testvectors_v1/%s (%d vectors)," % (file, len(rows)),
            "// sha256 %s." % hashlib.sha256(raw).hexdigest(),
            "// Copyright Google LLC and the Wycheproof contributors, Apache License 2.0 (see LICENSE).",
            "",
            "/** %s */" % layout,
            "internal val %s_VECTORS: Array<String> =" % name,
            "    arrayOf(",
        ]
        lines += ["        %s," % kotlin_string(row) for row in rows]
        lines += ["    )", ""]
        with open(os.path.join(OUT, "Wycheproof%s.kt" % kt), "w") as out:
            out.write("\n".join(lines))
        print("%-20s %4d vectors" % (name, len(rows)))


if __name__ == "__main__":
    main(sys.argv[1])
